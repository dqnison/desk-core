"""Moving rules in and out of a desk.

import — an existing CLAUDE.md (or AGENTS.md) split by `## ` sections into rule files
         `process/<slug>.md`, tier `import`: what was always in context stays so until
         you give a section its own `when:`. Nothing is overwritten.
export — rules for tools without the hook:
         agents-md     the `import` tier as one AGENTS.md (Codex, Cursor and others read it);
         claude-rules  rules whose every `when:` entry is `paths:` as `.claude/rules/*.md`
                       with a `paths:` field, which Claude Code loads natively on read/edit.
Guards and other triggers have no equivalent there and are not exported.
"""
import re
from pathlib import Path

from . import frontmatter, home as homelib


def slug(title):
    s = re.sub(r"[^\w\s-]", "", title.strip().lower())
    return re.sub(r"[\s_]+", "-", s).strip("-") or "section"


def sections(text):
    """[(title, body)] by `## ` headings; the text before the first one is ("", body)."""
    out, title, buf = [], "", []
    fence = False
    for line in frontmatter.body(text).splitlines():
        if line.lstrip().startswith("```"):
            fence = not fence
        if not fence and line.startswith("## "):
            if "".join(buf).strip():
                out.append((title, "\n".join(buf).strip()))
            title, buf = line[3:].strip(), []
        else:
            buf.append(line)
    if "".join(buf).strip():
        out.append((title, "\n".join(buf).strip()))
    return out


def import_file(source, home, prefix=""):
    """Split `source` into `process/<slug>.md` rules of DESK_HOME; [written paths]."""
    home = Path(home)
    (home / "process").mkdir(parents=True, exist_ok=True)
    written = []
    for title, body in sections(Path(source).read_text(encoding="utf-8")):
        name = slug(prefix + (title or Path(source).stem))
        dest, n = home / "process" / f"{name}.md", 2
        while dest.exists():
            dest, n = home / "process" / f"{name}-{n}.md", n + 1
        head = f"# {title}\n\n" if title else ""
        dest.write_text(f"---\ntier: import\n---\n\n{head}{body}\n", encoding="utf-8")
        written.append(dest)
    return written


def _paths_only(rule):
    entries = frontmatter.as_list(rule.fm.get("when"))
    return bool(entries) and all(isinstance(e, dict) and set(e) == {"paths"} for e in entries)


def export(home, fmt, out):
    """Write the export into folder `out`; [written paths]."""
    home, out = Path(home), Path(out)
    rules = [r for r in homelib.load_rules(home) if not r.error and r.enabled and r.context is None]
    written = []
    if fmt == "agents-md":
        parts = [f"<!-- generated by `desk export agents-md` from {r.rel} -->\n{r.body().strip()}"
                 for r in rules if r.tier == "import"]
        dest = out / "AGENTS.md"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text("\n\n".join(parts) + "\n", encoding="utf-8")
        written.append(dest)
    elif fmt == "claude-rules":
        for r in rules:
            if r.tier != "action" or not _paths_only(r):
                continue
            globs = [g for e in frontmatter.as_list(r.fm.get("when")) for g in frontmatter.as_list(e["paths"])]
            dest = out / ".claude" / "rules" / (Path(r.rel).stem + ".md")
            dest.parent.mkdir(parents=True, exist_ok=True)
            quoted = ", ".join(f'"{g}"' for g in globs)
            dest.write_text(f"---\npaths: [{quoted}]\n---\n<!-- generated by `desk export claude-rules` "
                            f"from {r.rel} -->\n\n{r.body().strip()}\n", encoding="utf-8")
            written.append(dest)
    else:
        raise ValueError(f"unknown format {fmt!r}: agents-md | claude-rules")
    return written
